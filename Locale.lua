function BF.Lang()
  local l = BananaFarmDB and BananaFarmDB.lang
  if l == "de" then return "deDE" end
  if l == "en" then return "enUS" end
  if GetLocale() == "deDE" then return "deDE" end
  return "enUS"
end

function BF.T(key)
  local t = BF.L[BF.Lang()]
  return t[key] or BF.L.enUS[key] or key
end

